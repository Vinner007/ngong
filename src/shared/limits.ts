// Every tunable number in the app lives here, next to the reason it has that value.

/** Longest confusion message. Long enough for one real question, short enough that nobody pastes an essay. */
export const QUESTION_MAX_LENGTH = 200

/** Room title, e.g. "Data Structures คาบ 3". */
export const TITLE_MAX_LENGTH = 60

/** Topic labels are shown inside bubbles and on phones, so they must stay short. */
export const LABEL_MAX_LENGTH = 60

/** A single-question topic uses the question itself as its label, cut to this length. */
export const QUESTION_LABEL_PREVIEW_LENGTH = 40

/** One message per device per 10 seconds stops button-mashing without slowing down an honest student. */
export const ASK_COOLDOWN_MS = 10_000

/** Hard caps per room. A real lecture never gets close; they only exist to bound abuse and storage. */
export const MAX_QUESTIONS_PER_ROOM = 2_000
export const MAX_TOPICS_PER_ROOM = 200
export const MAX_SOCKETS_PER_ROOM = 300

/** Rooms delete themselves after a day: the data is only useful during the lecture. */
export const ROOM_LIFETIME_MS = 24 * 60 * 60 * 1000

/** The confusion meter only counts people who joined a topic in this window, so it reflects "right now". */
export const CONFUSION_WINDOW_MS = 10 * 60 * 1000

/** Confusion meter bands, as a share of people online. */
export const CONFUSION_MEDIUM_FROM = 0.25
export const CONFUSION_HIGH_FROM = 0.5

/**
 * Cosine similarity at or above which a new question joins an existing topic.
 * Tuned with scripts/demo-questions.json (6 topics, 30 Thai questions) through /api/dev/tune.
 * With bge-m3, same-topic pairs average 0.61 and different-topic pairs 0.44, but the ranges
 * overlap. At 0.50 and below every question collapses into one topic; 0.51-0.54 mixes two
 * topics; 0.55-0.57 is a stable plateau with no mixed topics (9 found, some split in two);
 * from 0.58 up the splitting gets worse. 0.56 sits in the middle of the plateau. Splitting is
 * the safer mistake: two bubbles about one idea mislead the lecturer less than one bubble
 * about two ideas.
 */
export const SIMILARITY_THRESHOLD = 0.56

/** Embedding several pending questions in one call is cheaper and faster than one call each. */
export const EMBED_BATCH_SIZE = 16

/** Retries for questions whose embedding call failed, spaced by an alarm. */
export const MAX_PROCESSING_ATTEMPTS = 3
export const RETRY_DELAY_MS = 15_000

/**
 * Topic labels are regenerated by the LLM only when the topic grows to one of these sizes.
 * Fibonacci spacing relabels often while a topic is small (when the label matters most)
 * and rarely once it is large (when the label has settled).
 */
export const RELABEL_AT_SIZES = [2, 3, 5, 8, 13, 21, 34, 55, 89] as const

/** How many questions the LLM sees when naming a topic or suggesting a new explanation. */
export const LLM_SAMPLE_SIZE = 8

/** Many updates in a burst are merged into one broadcast so phones do not re-render 30 times a second. */
export const BROADCAST_DELAY_MS = 250

/** The host's "all questions" tab shows the most recent ones only. */
export const HOST_QUESTION_LIST_LIMIT = 200

/**
 * Pretend audience size while the classroom simulation runs. The simulation makes 44 pretend
 * students confused, so 80 in the room lands the meter around the middle, like a real class.
 */
export const DEMO_AUDIENCE_SIZE = 80
